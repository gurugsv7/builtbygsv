/**
 * Writes src/blogManifest.ts: route metadata for every article, without the article text.
 * The SPA's main bundle imports only this manifest; full articles load with the blog chunk.
 * Runs before every build; tests fail if the committed manifest drifts from src/blog.ts.
 */
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { blogPosts } from '../src/blog.ts';

const entries = blogPosts.map(({ path, title, seoTitle, description, published, updated }) =>
  ({ path, title, seoTitle, description, published, updated }));

const source = `// Generated by scripts/gen-blog-manifest.ts from src/blog.ts. Do not edit by hand.
export const blogManifest = ${JSON.stringify(entries, null, 2)} as const;
`;
await writeFile(resolve('src/blogManifest.ts'), source);
console.log(`Wrote blog manifest for ${entries.length} articles.`);
